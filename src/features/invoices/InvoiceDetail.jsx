// src/features/invoices/InvoiceDetail.jsx
import { useState, useEffect } from 'react';
import { useParams, useNavigate } from 'react-router-dom';
import { Button } from '../../components/ui';
import { Card } from '../../components/ui';
import { DataTable } from '../../components/ui';
import { Badge } from '../../components/ui';
import { MoneyText } from '../../components/ui';
import { PageHeader } from '../../components/ui';
import { Toast, ToastContainer } from '../../components/ui';
import { supabase } from '../../lib/supabaseClient';
import { statusLabel } from '../../lib/format';

export default function InvoiceDetail() {
  const { id } = useParams();
  const navigate = useNavigate();
  const [toasts, setToasts] = useState([]);
  const [inv, setInv] = useState(null);
  const [lines, setLines] = useState([]);
  const [printMode, setPrintMode] = useState(false);
  const [loading, setLoading] = useState(true);

  useEffect(() => { load(); }, [id]);

  const addToast = (msg, type = 'info') => {
    const n = Date.now();
    setToasts((t) => [...t, { id: n, msg, type }]);
    setTimeout(() => setToasts((ts) => ts.filter((x) => x.id !== n)), 4000);
  };

  async function load() {
    setLoading(true);
    const [iRes, lRes] = await Promise.all([
      supabase.from('invoices').select('*, subscriptions(number), customers(name, email)').eq('id', id).single(),
      supabase.from('invoice_lines').select('*').eq('invoice_id', id),
    ]);
    if (iRes.error) addToast(iRes.error.message, 'error');
    else setInv(iRes.data);
    if (lRes.error) addToast(lRes.error.message, 'error');
    else setLines(lRes.data || []);
    setLoading(false);
  }

  const outstanding = inv ? Math.max(0, Number(inv.total) - Number(inv.amount_paid)) : 0;

  const updateStatus = async (newStatus) => {
    const { error } = await supabase.from('invoices').update({ status: newStatus }).eq('id', id);
    if (error) addToast(error.message, 'error');
    else { addToast(`Invoice ${statusLabel(newStatus)}`, 'success'); load(); }
  };

  const sendInvoice = async () => {
    addToast('Invoice sent (simulated)', 'info');
  };

  const printInvoice = () => {
    setPrintMode(true);
    window.print();
    setPrintMode(false);
  };

  if (loading) return <div style={{ padding: 24, textAlign: 'center' }}>Loading...</div>;
  if (!inv) return <div style={{ padding: 24, textAlign: 'center' }}>Not found</div>;

  return (
    <div style={{ padding: 24 }}>
      <ToastContainer />
      {toasts.map((t) => (
        <Toast key={t.id} message={t.msg} type={t.type} onClose={() => setToasts((ts) => ts.filter((x) => x.id !== t.id))} />
      ))}
      {printMode && (
        <div className="invoice-print no-print">
          <div className="invoice-header">
            <div className="invoice-brand">Brightloop Billing</div>
            <div className="invoice-meta">
              <div><strong>Invoice {inv.number}</strong></div>
              <div>Issue date: {inv.issue_date}</div>
              <div>Due date: {inv.due_date}</div>
            </div>
          </div>
          <div className="invoice-customer">
            <h3>Bill to</h3>
            <div>{inv.customers?.name}</div>
            <div>{inv.customers?.email || '-'}</div>
          </div>
          <table className="invoice-table">
            <thead>
              <tr>
                <th>Description</th><th style={{ textAlign: 'right' }}>Qty</th>
                <th style={{ textAlign: 'right' }}>Unit price</th><th style={{ textAlign: 'right' }}>Amount</th>
              </tr>
            </thead>
            <tbody>
              {lines.map((l) => (
                <tr key={l.id}>
                  <td>{l.description}</td>
                  <td style={{ textAlign: 'right' }}>{l.quantity}</td>
                  <td style={{ textAlign: 'right' }}><MoneyText amount={l.unit_price} /></td>
                  <td style={{ textAlign: 'right' }}><MoneyText amount={l.amount} /></td>
                </tr>
              ))}
            </tbody>
          </table>
          <div className="invoice-totals">
            <table>
              <tr><td className="label">Subtotal</td><td><MoneyText amount={inv.subtotal} /></td></tr>
              <tr><td className="label">Discount</td><td><MoneyText amount={inv.discount_total} /></td></tr>
              <tr><td className="label">Tax</td><td><MoneyText amount={inv.tax_total} /></td></tr>
              <tr className="total-row"><td className="label">Total</td><td><MoneyText amount={inv.total} /></td></tr>
              <tr><td className="label">Amount paid</td><td><MoneyText amount={inv.amount_paid} /></td></tr>
              <tr><td className="label">Outstanding</td><td><MoneyText amount={outstanding} /></td></tr>
            </table>
          </div>
          <div className="invoice-footer">
            Thank you for your business. This invoice was generated by Brightloop Billing.
          </div>
        </div>
      )}
      {!printMode && (
        <>
          <PageHeader title={`Invoice ${inv.number}`} subtitle={inv.customers?.name || 'Customer'}>
            <div style={{ display: 'flex', gap: 8 }}>
              <Badge variant={inv.status === 'paid' ? 'success' : inv.status === 'overdue' || (inv.status === 'confirmed' && new Date(inv.due_date) < new Date()) ? 'danger' : 'info'}>
                {statusLabel(inv.status)}
              </Badge>
              <Button variant="ghost" size="sm" onClick={() => navigate('/invoices')}>Back</Button>
              <Button variant="outline" size="sm" onClick={printInvoice}>Print</Button>
            </div>
          </PageHeader>
          <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: 24, marginBottom: 24 }}>
            <Card>
              <h3 style={{ marginBottom: 12 }}>Details</h3>
              <p><strong>Customer:</strong> {inv.customers?.name}</p>
              <p><strong>Email:</strong> {inv.customers?.email}</p>
              <p><strong>Subscription:</strong> {inv.subscriptions?.number || '-'}</p>
              <p><strong>Period:</strong> {inv.period_start} to {inv.period_end}</p>
              <p><strong>Issue date:</strong> {inv.issue_date}</p>
              <p><strong>Due date:</strong> {inv.due_date}</p>
              <p><strong>Status:</strong> {statusLabel(inv.status)}</p>
              <p><strong>Outstanding:</strong> <MoneyText amount={outstanding} /></p>
            </Card>
            <Card>
              <h3 style={{ marginBottom: 12 }}>Actions</h3>
              <div style={{ display: 'flex', flexDirection: 'column', gap: 8 }}>
                {inv.status === 'draft' && <Button variant="primary" onClick={() => updateStatus('confirmed')}>Confirm</Button>}
                {inv.status === 'confirmed' && <Button variant="danger" onClick={() => updateStatus('cancelled')}>Cancel</Button>}
                {(inv.status === 'draft' || inv.status === 'confirmed') && <Button variant="info" onClick={sendInvoice}>Send (simulated)</Button>}
                <Button variant="outline" onClick={printInvoice}>Print</Button>
                <Button variant="primary" onClick={() => navigate(`/payments/new?invoice_id=${id}`)}>Record payment</Button>
              </div>
            </Card>
          </div>
          <Card>
            <h3 style={{ marginBottom: 12 }}>Lines</h3>
            <DataTable
              columns={[
                { key: 'description', label: 'Description' },
                { key: 'quantity', label: 'Qty' },
                { key: 'unit_price', label: 'Unit price', render: (r) => <MoneyText amount={r.unit_price} /> },
                { key: 'tax_amount', label: 'Tax', render: (r) => <MoneyText amount={r.tax_amount} /> },
                { key: 'amount', label: 'Amount', render: (r) => <MoneyText amount={r.amount} /> },
              ]}
              data={lines}
            />
            <div style={{ marginTop: 12, textAlign: 'right' }}>
              <div>Subtotal: <MoneyText amount={inv.subtotal} /></div>
              <div>Discount: <MoneyText amount={inv.discount_total} /></div>
              <div>Tax: <MoneyText amount={inv.tax_total} /></div>
              <div style={{ fontWeight: 700, fontSize: 16, marginTop: 6 }}>Total: <MoneyText amount={inv.total} /></div>
              <div style={{ fontWeight: 700 }}>Paid: <MoneyText amount={inv.amount_paid} /></div>
              <div style={{ fontWeight: 700, color: outstanding > 0 ? 'var(--danger)' : 'var(--success)' }}>Outstanding: <MoneyText amount={outstanding} /></div>
            </div>
          </Card>
        </>
      )}
    </div>
  );
}
